-- 1. Create Testimonials Table
CREATE TABLE IF NOT EXISTS public.testimonials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    service_received TEXT,
    star_rating INTEGER NOT NULL CHECK (star_rating BETWEEN 1 AND 5),
    review_text TEXT NOT NULL,
    approval_status TEXT NOT NULL DEFAULT 'pending' 
        CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.testimonials ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Public Visitors Can Submit Reviews (Must be 'pending')
DROP POLICY IF EXISTS "Visitors can submit testimonials" ON public.testimonials;
CREATE POLICY "Visitors can submit testimonials"
ON public.testimonials
FOR INSERT
TO anon, authenticated
WITH CHECK (
    approval_status = 'pending'
);

-- 4. Policy: Public Visitors Can ONLY View Approved Reviews
DROP POLICY IF EXISTS "Visitors can view approved testimonials" ON public.testimonials;
CREATE POLICY "Visitors can view approved testimonials"
ON public.testimonials
FOR SELECT
TO anon, authenticated
USING (
    approval_status = 'approved'
);

-- 5. Policy: Authenticated Admins Can View ALL Reviews (Pending, Approved, Rejected)
DROP POLICY IF EXISTS "Admins can view all testimonials" ON public.testimonials;
CREATE POLICY "Admins can view all testimonials"
ON public.testimonials
FOR SELECT
TO authenticated
USING (true);

-- 6. Policy: Authenticated Admins Can Approve or Reject Reviews
DROP POLICY IF EXISTS "Admins can update testimonial status" ON public.testimonials;
CREATE POLICY "Admins can update testimonial status"
ON public.testimonials
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

-- 7. Policy: Authenticated Admins Can Delete Reviews
DROP POLICY IF EXISTS "Admins can delete testimonials" ON public.testimonials;
CREATE POLICY "Admins can delete testimonials"
ON public.testimonials
FOR DELETE
TO authenticated
USING (true);

